# Genuine-prompt extraction and the skip-list


def test_returns_most_recent_genuine_prompt(tmp_path):
    proj = make_transcript(
        tmp_path,
        [user_line("older prompt"), assistant_line(), user_line("newest prompt")],
    )
    assert transcript.last_prompt(SID, CWD, proj) == "newest prompt"


def test_skips_tool_results(tmp_path):
    proj = make_transcript(
        tmp_path, [user_line("real prompt"), tool_result_line(), tool_result_line()]
    )
    assert transcript.last_prompt(SID, CWD, proj) == "real prompt"


def test_skips_command_wrapper_messages(tmp_path):
    proj = make_transcript(
        tmp_path,
        [
            user_line("real prompt"),
            user_line("<command-name>/clear</command-name>"),
            user_line("<local-command-stdout>output</local-command-stdout>"),
            user_line("Caveat: the messages below were generated by the user"),
        ],
    )
    assert transcript.last_prompt(SID, CWD, proj) == "real prompt"


def test_skips_task_notifications(tmp_path):
    proj = make_transcript(
        tmp_path,
        [user_line("real prompt"), user_line("<task-notification>\ndone\n</task-notification>")],
    )
    assert transcript.last_prompt(SID, CWD, proj) == "real prompt"


def test_skips_system_reminder_only_and_strips_embedded(tmp_path):
    proj = make_transcript(
        tmp_path,
        [
            user_line("real prompt <system-reminder>secret plumbing</system-reminder> tail"),
            user_line("<system-reminder>\nonly plumbing here\n</system-reminder>"),
        ],
    )
    got = transcript.last_prompt(SID, CWD, proj)
    assert got == "real prompt tail"
    assert "plumbing" not in got


def test_skips_compaction_continuation_summaries(tmp_path):
    proj = make_transcript(
        tmp_path,
        [
            user_line("real prompt"),
            user_line(
                "This session is being continued from a previous conversation"
                " that ran out of context. Summary follows."
            ),
            user_line("flagged summary", isCompactSummary=True),
        ],
    )
    assert transcript.last_prompt(SID, CWD, proj) == "real prompt"


def test_skips_meta_sidechain_and_non_user_roles(tmp_path):
    proj = make_transcript(
        tmp_path,
        [
            user_line("real prompt"),
            user_line("stop-hook feedback", isMeta=True),
            user_line("sidechain chatter", isSidechain=True),
            assistant_line("assistant text is never a prompt"),
            json.dumps({"type": "queue-operation", "operation": "enqueue"}),
        ],
    )
    assert transcript.last_prompt(SID, CWD, proj) == "real prompt"


def test_truncates_and_collapses_whitespace(tmp_path):
    long = ("word " * 100).strip()
    proj = make_transcript(tmp_path, [user_line("a\n\n  b\t" + long)])
    got = transcript.last_prompt(SID, CWD, proj)
    assert got is not None
    assert len(got) <= 121
    assert got.startswith("a b word")
    assert got.endswith("…")
    assert "\n" not in got


def test_missing_transcript_returns_none(tmp_path):
    assert transcript.last_prompt(SID, CWD, tmp_path / "nope") is None


def test_all_garbage_returns_none(tmp_path):
    proj = make_transcript(tmp_path, [tool_result_line(), assistant_line()])
    assert transcript.last_prompt(SID, CWD, proj) is None


