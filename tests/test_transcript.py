import json

from crr import transcript

SID = "11111111-2222-3333-4444-555555555555"
CWD = "/home/u/my.project"


def user_line(text, **extra):
    obj = {"type": "user", "message": {"role": "user", "content": text}}
    obj.update(extra)
    return json.dumps(obj)


def tool_result_line():
    return json.dumps(
        {
            "type": "user",
            "message": {
                "role": "user",
                "content": [
                    {"type": "tool_result", "tool_use_id": "t1", "content": "ok"}
                ],
            },
        }
    )


def assistant_line(text="I did the thing"):
    return json.dumps(
        {
            "type": "assistant",
            "message": {"role": "assistant", "content": [{"type": "text", "text": text}]},
        }
    )


def make_transcript(tmp_path, lines, sid=SID, cwd=CWD):
    proj = tmp_path / "projects"
    d = proj / transcript.cwd_slug(cwd)
    d.mkdir(parents=True, exist_ok=True)
    (d / (sid + ".jsonl")).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return proj


# ---------------------------------------------------------------------------
# Slug + path safety


def test_cwd_slug_maps_non_alnum_to_dash():
    # Verified against a real ~/.claude/projects: /home/user -> -home-user
    assert transcript.cwd_slug("/home/user") == "-home-user"
    assert transcript.cwd_slug("/home/u/my.project") == "-home-u-my-project"


def test_transcript_path_rejects_non_uuid_sid(tmp_path):
    assert transcript.transcript_path("../../etc/passwd", CWD, tmp_path) is None
    assert transcript.transcript_path("not-a-uuid", CWD, tmp_path) is None
    assert transcript.transcript_path("", CWD, tmp_path) is None
    path = transcript.transcript_path(SID, CWD, tmp_path)
    assert path is not None and path.name == SID + ".jsonl"


