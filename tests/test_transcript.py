# Backwards streaming


def test_backwards_streaming_multi_block_padding_prefix(tmp_path):
    """A multi-block pile of non-prompt lines before the genuine prompt:
    the extractor must find the prompt reading backwards without loading
    the file, and block-boundary line splits must reassemble correctly."""
    block = 512
    padding = [assistant_line("pad " + ("x" * 200))] * 50  # ~10KB >> several blocks
    lines = padding + [user_line("the genuine one")] + [tool_result_line()] * 3
    proj = make_transcript(tmp_path, lines)
    got = transcript.last_prompt(SID, CWD, proj, block_size=block)
    assert got == "the genuine one"


def test_line_longer_than_block_reassembled(tmp_path):
    """A single JSON line spanning many read blocks parses intact."""
    big_prompt = "start " + ("y" * 5000) + " end"
    proj = make_transcript(
        tmp_path, [user_line("older"), user_line(big_prompt), tool_result_line()]
    )
    got = transcript.last_prompt(SID, CWD, proj, block_size=256)
    assert got is not None
    assert got.startswith("start yyy")


def test_max_bytes_early_exit(tmp_path):
    """Only the file tail is scanned: a prompt buried beyond max_bytes is
    not found (the whole file is never read)."""
    lines = [user_line("buried far too deep")] + [assistant_line("z" * 300)] * 40
    proj = make_transcript(tmp_path, lines)
    got = transcript.last_prompt(SID, CWD, proj, block_size=256, max_bytes=1024)
    assert got is None
